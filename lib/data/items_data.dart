/// Shorthand for an equipment entry.
ItemDef _gear({
  required String id,
  required String name,
  required EquipSlot slot,
  required ItemRarity rarity,
  required int levelReq,
  required IconData icon,
  required StatBundle bonuses,
  required int sellValue,
  String description = '',
  WeaponLook? look,
  ItemSetId? setId,
}) => ItemDef(
  id: id,
  name: name,
  description: description,
  kind: ItemKind.equipment,
  rarity: rarity,
  icon: icon,
  slot: slot,
  levelReq: levelReq,
  bonuses: bonuses,
  sellValue: sellValue,
  weaponLook: look,
  setId: setId,
);

