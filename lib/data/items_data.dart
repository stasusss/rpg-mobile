/// All items keyed by id.
final Map<String, ItemDef> itemCatalog = {
  for (final item in _allItems) item.id: item,
};

/// Lookup that throws a helpful error for unknown ids instead of a null crash.
ItemDef itemById(String id) {
  final item = itemCatalog[id];
  if (item == null) throw StateError('Unknown item id: $id');
  return item;
}

ItemDef? tryItemById(String id) => itemCatalog[id];

