/// All enemies keyed by id.
final Map<String, EnemyDef> enemyCatalog = {
  for (final e in _allEnemies) e.id: e,
};

EnemyDef enemyById(String id) {
  final e = enemyCatalog[id];
  if (e == null) throw StateError('Unknown enemy id: $id');
  return e;
}

/// Bestiary display order.
List<EnemyDef> get allEnemiesByLevel =>
    _allEnemies.toList()..sort((a, b) => a.level.compareTo(b.level));

/// Enemy ids that can drop [itemId], for the "where do I farm this?" hint.
List<EnemyDef> enemiesDropping(String itemId) =>
    _allEnemies.where((e) => e.loot.any((d) => d.itemId == itemId)).toList()
      ..sort((a, b) => a.level.compareTo(b.level));

/// Best base drop chance for [itemId] across the bestiary.
double bestDropChance(String itemId) {
  var best = 0.0;
  for (final e in _allEnemies) {
    for (final d in e.loot) {
      if (d.itemId == itemId && d.chance > best) best = d.chance;
    }
  }
  return best;
}

