List<CraftRecipe> get allRecipes => _allRecipes;

final Map<String, CraftRecipe> recipeCatalog = {
  for (final r in _allRecipes) r.id: r,
};

/// Recipes sorted so the ones the player can almost afford surface first.
List<CraftRecipe> recipesForLevel(int level) =>
    _allRecipes.where((r) => r.requiredLevel <= level + 4).toList()
      ..sort((a, b) => a.requiredLevel.compareTo(b.requiredLevel));
