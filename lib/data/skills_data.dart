List<SkillDef> get allSkills => _allSkills;

final Map<String, SkillDef> skillCatalog = {
  for (final s in _allSkills) s.id: s,
};

final Map<String, SkillDef> signatureCatalog = {
  for (final s in signatureSkills) s.id: s,
};

SkillDef? trySkillById(String id) => skillCatalog[id] ?? signatureCatalog[id];

SkillDef skillById(String id) {
  final s = trySkillById(id);
  if (s == null) throw StateError('Unknown skill id: $id');
  return s;
}

List<SkillDef> skillsInBranch(SkillBranch branch) =>
    _allSkills.where((s) => s.branch == branch).toList()
      ..sort((a, b) => a.row.compareTo(b.row));

int get skillTreeColumns =>
    _allSkills.map((s) => s.col).reduce((a, b) => a > b ? a : b) + 1;

int get skillTreeRows =>
    _allSkills.map((s) => s.row).reduce((a, b) => a > b ? a : b) + 1;

/// Kept for older layout helpers; equals [skillTreeRows].
int get skillTreeDepth => skillTreeRows;
